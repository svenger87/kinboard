#!/usr/bin/env node
/**
 * build-store-listings.mjs: every app-store listing, from one metadata file
 * (RFC-024 §7).
 *
 *   node scripts/stores/build-store-listings.mjs           write dist/<store>/…
 *   node scripts/stores/build-store-listings.mjs --check   change nothing; exit 1
 *                                                          when dist/ is not what
 *                                                          the inputs generate, or
 *                                                          a listing fails a check
 *
 * Inputs: the metadata file in dist/, compose.yml and docker.yml
 * (lib/sources.mjs). Outputs, each in its store's own format and layout:
 *
 *   dist/truenas/ix-dev/community/<app>/…   TrueNAS apps catalog
 *   dist/casaos/Apps/<Name>/docker-compose.yml   CasaOS / ZimaOS
 *   dist/umbrel/<app>/…                     Umbrel app store
 *   dist/portainer/templates.json, compose.yml   Portainer app templates
 *
 * Then our own checks over what was generated (lib/checks.mjs): the image
 * names are docker.yml's, the database is the stock image with safeupdate,
 * no secrets, every volume where its store wants it, every variable of
 * compose.yml present, every text the metadata's. The store's own linters
 * run in scripts/stores/validate-upstream.sh.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { casaos } from "./lib/casaos.mjs";
import { listingProblems } from "./lib/checks.mjs";
import { portainer } from "./lib/portainer.mjs";
import { DIST, loadSources, REPO_ROOT } from "./lib/sources.mjs";
import { truenas } from "./lib/truenas.mjs";
import { umbrel } from "./lib/umbrel.mjs";

/** The store folders under dist/ this generator owns entirely. */
export const STORES = ["truenas", "casaos", "umbrel", "portainer"];

/**
 * Every generated file, by its path under dist/.
 * @param {ReturnType<typeof loadSources>} src
 * @returns {Record<string, string>}
 */
export function buildListings(src) {
  return { ...truenas(src), ...casaos(src), ...umbrel(src), ...portainer(src) };
}

/** The files under dist/<store>/ on disk, by their path under dist/. */
export function filesOnDisk(root = REPO_ROOT) {
  const out = {};
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else out[relative(join(root, DIST), p)] = readFileSync(p, "utf8");
    }
  };
  for (const store of STORES) if (existsSync(join(root, DIST, store))) walk(join(root, DIST, store));
  return out;
}

/**
 * The differences between generated and committed files, as sentences.
 * @param {Record<string, string>} generated
 * @param {Record<string, string>} onDisk
 */
export function driftProblems(generated, onDisk) {
  const p = [];
  for (const [path, text] of Object.entries(generated)) {
    if (!(path in onDisk)) p.push(`${DIST}/${path} is missing`);
    else if (onDisk[path] !== text) p.push(`${DIST}/${path} differs from what the metadata generates`);
  }
  for (const path of Object.keys(onDisk)) if (!(path in generated)) p.push(`${DIST}/${path} is not generated by anything (stale)`);
  return p;
}

function main(argv) {
  const check = argv.includes("--check");
  let src;
  let generated;
  try {
    src = loadSources(REPO_ROOT);
    generated = buildListings(src);
  } catch (err) {
    process.stderr.write(`build-store-listings: ${err?.message ?? err}\n`);
    process.exit(1);
  }
  if (check) {
    // The committed files, read back as a store would: a hand edit fails with
    // the reason, not only as a difference.
    const onDisk = filesOnDisk(REPO_ROOT);
    const problems = [...driftProblems(generated, onDisk), ...listingProblems(onDisk, src)];
    if (problems.length) {
      process.stderr.write(`build-store-listings --check: ${problems.length} problem(s)\n${problems.map((x) => `  - ${x}`).join("\n")}\n`);
      process.stderr.write("Run `node scripts/stores/build-store-listings.mjs` and commit dist/.\n");
      process.exit(1);
    }
    process.stdout.write(`build-store-listings --check: ${Object.keys(generated).length} files up to date, every check passed\n`);
    return;
  }
  const problems = listingProblems(generated, src);
  if (problems.length) {
    process.stderr.write(`build-store-listings: the generated listings fail ${problems.length} check(s)\n${problems.map((x) => `  - ${x}`).join("\n")}\n`);
    process.exit(1);
  }
  for (const store of STORES) rmSync(join(REPO_ROOT, DIST, store), { recursive: true, force: true });
  for (const [path, text] of Object.entries(generated)) {
    const file = join(REPO_ROOT, DIST, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  process.stdout.write(`build-store-listings: wrote ${Object.keys(generated).length} files under ${DIST}/\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main(process.argv.slice(2));
