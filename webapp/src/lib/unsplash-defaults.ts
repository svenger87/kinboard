function sameTerms(a: readonly string[], b: readonly string[]): boolean {
  return a.length === b.length && a.every((t, i) => t === b[i]);
}

/** True when a saved month is just a copy of what some release shipped. */
function isUneditedCopy(month: string, saved: readonly string[]): boolean {
  const current = DEFAULT_MONTHLY_TERMS[month] ?? [];
  const former = FORMER_DEFAULT_TERMS[month] ?? [];
  return (
    sameTerms(saved, current) ||
    sameTerms(saved, former) ||
    sameTerms(saved, former.slice(0, 8))
  );
}

/**
 * The terms a month actually uses: the household's own list when they edited
 * it, otherwise the current defaults. Older saved formats (a single string)
 * and empty lists fall back to the defaults too.
 */
export function termsForMonth(
  saved: Record<string, unknown> | null | undefined,
  month: string,
): string[] {
  const own = saved?.[month];
  if (Array.isArray(own)) {
    const list = own.filter((t): t is string => typeof t === "string" && t.trim() !== "");
    if (list.length > 0 && !isUneditedCopy(month, list)) return list;
  }
  return [...(DEFAULT_MONTHLY_TERMS[month] ?? [])];
}

/** Every month's effective terms, for the settings editor. */
export function allMonthTerms(
  saved: Record<string, unknown> | null | undefined,
): Record<string, string[]> {
  return Object.fromEntries(
    Object.keys(DEFAULT_MONTHLY_TERMS).map((m) => [m, termsForMonth(saved, m)]),
  );
}

/**
 * What to store: only the months someone changed. A month left alone keeps
 * following the defaults, so a later release's better list reaches it.
 */
export function customizedTerms(terms: Record<string, string[]>): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const [month, list] of Object.entries(terms)) {
    if (list.length > 0 && !isUneditedCopy(month, list)) out[month] = list;
  }
  return out;
}

