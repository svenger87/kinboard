/**
 * Every festival kit (lib/festivals/kits/, RFC-020): the rules a festival has
 * to keep to be added by its own files alone (docs/festivals/ADDING-A-FESTIVAL.md).
 * Its files are where they belong and the registry is one line each; its
 * dressing is scoped to itself and to Animations On and Reduced; its art is
 * all there and generated by its script; its outfit is a shop item or its
 * own; its stages are what it says. Pure; no stack.
 */

const read = (file: string) => readFileSync(join(process.cwd(), file), "utf8");
const kits = Object.values(FESTIVAL_KITS) as FestivalKit[];

test("one file per festival, and the registry one line each, alphabetical", () => {
  const registry = read("src/lib/festivals/kits/all.ts");
  const lines = registry.split("\n").filter((l) => l.startsWith("export "));
  // Nothing but the one-line exports: two festivals added at once merge cleanly.
  expect(registry.split("\n").filter((l) => l.trim() && !l.startsWith("export ") && !/^\s*(\/\*\*|\*)/.test(l))).toEqual([]);
  const files = lines.map((l) => /^export \{ default as \w+ \} from "\.\/([a-z0-9-]+)";$/.exec(l)?.[1]);
  for (const [i, file] of files.entries()) expect(file, lines[i]).toBeTruthy();
  expect(files, "alphabetical").toEqual([...files].sort());
  expect(files.length).toBe(kits.length);
  for (const kit of kits) {
    expect(FESTIVALS, kit.id).toContain(kit.id);
    // The file is named for the festival.
    expect(files, kit.id).toContain(kit.id);
    expect(existsSync(`src/lib/festivals/kits/${kit.id}.ts`) || existsSync(`src/lib/festivals/kits/${kit.id}.tsx`), kit.id).toBe(true);
  }
  expect(DRAWN_FESTIVALS.length).toBe(kits.length);
  expect(BUILT_FESTIVALS.every((id) => !FESTIVAL_KITS[id]?.draft)).toBe(true);
});

/** The selectors of a stylesheet, at any depth (an @media block's too). */
function selectors(css: string): string[] {
  const out: string[] = [];
  const body = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let depth = 0;
  let start = 0;
  for (let i = 0; i < body.length; i++) {
    if (body[i] === "{") {
      const head = body.slice(start, i).trim();
      if (!head.startsWith("@")) out.push(...head.split(",").map((s) => s.trim()));
      depth++;
      start = i + 1;
    } else if (body[i] === "}") {
      depth--;
      start = i + 1;
    } else if (body[i] === ";" && depth > 0) {
      start = i + 1;
    }
  }
  return out.filter(Boolean);
}

test("a kit's wash and dressing touch only its own festival, and the dressing only with Animations On or Reduced", () => {
  for (const kit of kits) {
    const own = `:root[data-festival="${kit.id}"]`;
    const ownDark = `:root.dark[data-festival="${kit.id}"]`;
    for (const sel of selectors(kitCss(kit))) {
      expect(sel.startsWith(own) || sel.startsWith(ownDark), `${kit.id}: ${sel}`).toBe(true);
    }
    const dressing = kit.dressing ? kit.dressing(dressingSelectors(kit.id, kit.art)) : "";
    for (const sel of selectors(dressing)) {
      // Still, so Reduced keeps it; Off leaves the colour wash only (§4).
      expect(sel, `${kit.id}: ${sel}`).toContain(':not([data-motion="off"])');
      // Never catching a tap meant for the card under it, never over the whole screen.
      expect(sel, `${kit.id}: ${sel}`).not.toMatch(/(^|\s)(body|main|html)\b/);
    }
    // A pseudo-element dressing never takes a tap.
    for (const block of dressing.split("}")) {
      if (/::(before|after)\s*\{[^]*content:/.test(block)) expect(block, `${kit.id}: pointer-events`).toContain("pointer-events: none");
    }
    // The wash: two HSL colours, light and dark, never the month's strengths (contrast doesn't change, §2.4).
    for (const [top, bottom] of [kit.wash.light, kit.wash.dark, ...Object.values(kit.washByStage ?? {}).flatMap((w) => [w.light, w.dark])]) {
      for (const c of [top, bottom]) expect(c, kit.id).toMatch(/^\d{1,3} \d{1,3}% \d{1,3}%$/);
    }
    expect(kitCss(kit), kit.id).not.toContain("--month-wash");
  }
  // All of them, in the page from the first paint, as the text of a <style>: nothing that could close it.
  expect(FESTIVAL_CSS).not.toContain("</");
  for (const kit of kits) expect(FESTIVAL_CSS).toContain(kitCss(kit));
  expect(read("src/app/layout.tsx")).toContain('<style id="festival-css" dangerouslySetInnerHTML={{ __html: FESTIVAL_CSS }} />');
  // And none of it left in globals.css, where two festivals added at once would collide.
  expect(read("src/app/globals.css")).not.toMatch(/:root\[data-festival="[a-z-]+"\]/);
});

/** Every part a visitor's body or members draw. */
function partsOf(spec: VisitorSpec): string[] {
  const ofNode = (n: RigNode): string[] => [...(n.part ? [n.part] : []), ...(n.under ?? []).flatMap(ofNode), ...(n.over ?? []).flatMap(ofNode)];
  const ofBody = (b: Body) => (typeof b === "string" ? [b] : ofNode(b.root));
  switch (spec.archetype) {
    case "fly":
      return ofBody(spec.body);
    case "walk":
      return spec.members.flatMap(ofBody);
    case "rise":
    case "drift":
    case "burst":
      return spec.sprites;
    case "fireworks":
      return spec.sprites ?? [];
    case "arc":
      return [spec.sprite, ...(spec.sparkle ? [spec.sparkle] : [])];
  }
}

const svg = (file: string) => existsSync(file) && read(file).startsWith('<svg xmlns="http://www.w3.org/2000/svg"');

test("every drawing a kit uses is there, as SVG, and comes from its art script", () => {
  for (const kit of kits) {
    for (const stage of Object.keys(kit.visitorByStage ?? {})) expect(kit.stages, `${kit.id}: a visitor for its own stage ${stage}`).toContain(stage);
    for (const v of [kit.visitor, ...Object.values(kit.visitorByStage ?? {})]) {
      if (!v) continue;
      expect(v.size.min, kit.id).toBeLessThanOrEqual(v.size.max);
      expect(v.size.min, kit.id).toBeGreaterThan(0);
      for (const part of partsOf(v)) {
        expect(v.parts?.[part], `${kit.id}: ${part} in its art.json`).toBeTruthy();
        expect(svg(`public/festivals/${v.art ?? kit.id}/${part}.svg`), `${kit.id}: ${part}.svg`).toBe(true);
      }
      for (const part of Object.keys(v.parts ?? {})) expect(svg(`public/festivals/${v.art ?? kit.id}/${part}.svg`), `${kit.id}: ${part}.svg`).toBe(true);
    }
    // The dressing's drawings.
    const dressing = kit.dressing ? kit.dressing(dressingSelectors(kit.id, kit.art)) : "";
    for (const [, path] of dressing.matchAll(/url\("(\/festivals\/[^"]+)"\)/g)) {
      // Its own folder, the one it borrows, or its visitor's (Orthodox Easter hangs Easter's bunting).
      const folders = [kit.id, kit.art, kit.visitor?.art].filter(Boolean);
      expect(folders.some((f) => path.startsWith(`/festivals/${f}/`)), `${kit.id}: ${path} from its own folder, the one it borrows, or its visitor's`).toBe(true);
      expect(svg(`public${path}`), `${kit.id}: ${path}`).toBe(true);
    }
  }
  // Every art folder is a kit's (or one it borrows), and has its script.
  const borrowed = new Set(kits.flatMap((k) => [k.visitor?.art, k.art, ...Object.values(k.visitorByStage ?? {}).map((v) => v?.art)]).filter(Boolean));
  for (const dir of readdirSync("public/festivals")) {
    expect(FESTIVAL_KITS[dir as keyof typeof FESTIVAL_KITS] || borrowed.has(dir as never), `public/festivals/${dir}`).toBeTruthy();
    expect(existsSync(`scripts/festival-art/${dir}.py`), `scripts/festival-art/${dir}.py`).toBe(true);
  }
  for (const file of readdirSync("src/lib/festivals/kits").filter((f) => f.endsWith(".art.json"))) {
    expect(existsSync(`scripts/festival-art/${file.replace(".art.json", ".py")}`), file).toBe(true);
  }
});

test("an outfit is the shop's item for its slot, or the festival's own, drawn, under a name of its own (or borrowed whole)", () => {
  const seen = new Map<string, string>();
  const drawn = new Map<string, unknown>();
  for (const kit of kits) {
    const slots = new Set<string>();
    for (const item of kit.outfit) {
      expect(slots.has(item.slot), `${kit.id}: one item a slot`).toBe(false);
      slots.add(item.slot);
      if (item.draw) {
        // Its own: never a shop id, never another festival's.
        expect(isItemFor(item.slot, item.item), `${kit.id}: ${item.item} is a shop id`).toBe(false);
        // Another festival's under the same name only when it is that very item (Orthodox Christmas wears Christmas's Santa hat).
        if (seen.has(item.item) && seen.get(item.item) !== kit.id) expect(drawn.get(item.item), `${kit.id}: ${item.item} is ${seen.get(item.item)}'s`).toBe(item.draw);
        else seen.set(item.item, kit.id);
        drawn.set(item.item, item.draw);
      } else {
        expect(isItemFor(item.slot, item.item), `${kit.id}: ${item.item} isn't the shop's ${item.slot} item`).toBe(true);
      }
    }
  }
});

test("a kit's stages are the ones it names, on every day of its windows", () => {
  for (const kit of kits) {
    if (kit.previewStage) expect(kit.stages, kit.id).toContain(kit.previewStage);
    for (const s of kit.stages ?? []) expect(s, kit.id).toMatch(/^[a-z0-9-]{1,24}$/);
    if (!kit.stage) continue;
    expect(kit.stages?.length, `${kit.id} names its stages`).toBeGreaterThan(0);
    for (const country of ["DE", "US", "FR", "MX"]) {
      for (const w of festivalDates(kit.id, 2027, country)) {
        for (let d = w.start; d <= w.end; d = new Date(Date.parse(`${d}T12:00:00Z`) + 86_400_000).toISOString().slice(0, 10)) {
          for (const hour of [9, 21]) {
            const on = activeFestival(new Date(`${d}T${String(hour).padStart(2, "0")}:00:00Z`), [kit.id], "UTC", { country });
            if (!on) continue;
            const stage = festivalStage(on, country);
            if (stage !== null) expect(kit.stages, `${kit.id} ${d} ${hour}h`).toContain(stage);
          }
        }
      }
    }
  }
});
