import { test, expect } from "@playwright/test";
import { execFileSync, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

/**
 * Discussion #539: a git install on OpenMediaVault lost webapp/docker/.env.
 * OpenMediaVault's Compose plugin deletes .env in a folder it manages (or
 * links it to its own copy), and the obvious next step, `./setup.sh`, made a
 * new .env with new passwords. The database only accepts the password it was
 * created with, so the install then stopped at kinboard-db-init ("password
 * authentication failed for user supabase_admin"), data intact and out of
 * reach. setup.sh's own push-key hint said `--force`, which does the same to
 * an install that still has its .env.
 *
 * Now setup.sh stops before writing anything when a new .env (none there, or
 * --force) would meet an existing database, unless --new-passwords says so on
 * purpose; start.sh says where .env went when OpenMediaVault manages the
 * folder. These run both scripts on a copy of the tracked files.
 */

const REPO = resolve(__dirname, "../..");
const OMV_HEADER = "# This file is auto-generated by openmediavault (https://www.openmediavault.org)\n# WARNING: Do not edit this file, your changes will get lost.\n";

/** A copy of the tracked files, plus a bin folder whose npx prints fixed push keys (no network). */
function checkout() {
  const dir = mkdtempSync(join(tmpdir(), "setup-db-"));
  execFileSync("bash", ["-c", `cd "$1" && git ls-files -z | tar --null -T - -c | tar -x -C "$2"`, "_", REPO, dir]);
  const bin = join(dir, ".bin");
  mkdirSync(bin);
  writeFileSync(join(bin, "npx"), `#!/bin/sh\necho '{"publicKey":"BTestPublicKey","privateKey":"testPrivateKey"}'\n`);
  chmodSync(join(bin, "npx"), 0o755);
  const docker = join(dir, "webapp/docker");
  return { dir, bin, docker, env: join(docker, ".env") };
}

/** A db folder as PostgreSQL leaves it: PG_VERSION and a subfolder. */
function database(at: string) {
  mkdirSync(join(at, "base"), { recursive: true });
  writeFileSync(join(at, "PG_VERSION"), "15\n");
}

function setup(c: ReturnType<typeof checkout>, args: string[] = [], extra: Record<string, string> = {}) {
  const env: NodeJS.ProcessEnv = { ...process.env, PATH: `${c.bin}:${process.env.PATH}`, KINBOARD_URL: "", ...extra };
  if (!("DATA_DIR" in extra)) delete env.DATA_DIR;
  return spawnSync("bash", ["./setup.sh", "--non-interactive", ...args], { cwd: c.dir, encoding: "utf8", env, timeout: 60_000 });
}

function startSh(c: ReturnType<typeof checkout>, cmd = "status") {
  // docker and docker-compose stand-ins: start.sh only has to get past its checks.
  for (const tool of ["docker", "docker-compose"]) {
    writeFileSync(join(c.bin, tool), "#!/bin/sh\nexit 0\n");
    chmodSync(join(c.bin, tool), 0o755);
  }
  return spawnSync("bash", [join(c.docker, "start.sh"), cmd], {
    cwd: c.docker,
    encoding: "utf8",
    env: { ...process.env, PATH: `${c.bin}:/usr/bin:/bin`, COMPOSE_FILES: "", PROJECT_NAME: "" },
    timeout: 30_000,
  });
}

const sha = (p: string) => createHash("sha256").update(readFileSync(p)).digest("hex");
const key = (p: string, k: string) => readFileSync(p, "utf8").match(new RegExp(`^${k}=(.*)$`, "m"))?.[1] ?? "";

test.describe("setup.sh beside an existing database", () => {
  test("no .env and data/db holds a database: stops, writes nothing, names the copies", () => {
    const c = checkout();
    try {
      database(join(c.docker, "data/db"));
      writeFileSync(join(c.docker, ".env.keep"), "POSTGRES_PASSWORD=old\n");
      writeFileSync(join(c.docker, ".env.notes"), "nothing secret here\n");
      const r = setup(c);
      expect(r.status, r.stdout + r.stderr).toBe(1);
      // Nothing written: no .env, no webapp/.env.local, not even the lock.
      for (const f of [c.env, join(c.dir, "webapp/.env.local"), join(c.docker, ".env.lock")]) expect(existsSync(f), f).toBe(false);
      expect(r.stderr).toContain("already holds this install's database");
      expect(r.stderr).toContain(".env.keep");
      expect(r.stderr).not.toContain(".env.notes");
      expect(r.stderr).toContain("--new-passwords");
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test("a db folder this user can't look into counts as a database", () => {
    test.skip(process.getuid?.() === 0, "root can look into any folder");
    const c = checkout();
    const db = join(c.docker, "data/db");
    try {
      database(db);
      chmodSync(db, 0o000);
      const r = setup(c);
      expect(r.status, r.stdout + r.stderr).toBe(1);
      expect(existsSync(c.env)).toBe(false);
    } finally {
      chmodSync(db, 0o755);
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test("no database, or an empty db folder: a new install goes ahead as before", () => {
    for (const make of [() => {}, (c: ReturnType<typeof checkout>) => mkdirSync(join(c.docker, "data/db"), { recursive: true })]) {
      const c = checkout();
      try {
        make(c);
        const r = setup(c);
        expect(r.status, r.stdout + r.stderr).toBe(0);
        expect(key(c.env, "POSTGRES_PASSWORD")).toMatch(/^[0-9a-f]{64}$/);
      } finally {
        rmSync(c.dir, { recursive: true, force: true });
      }
    }
  });

  test("--new-passwords makes the new .env anyway", () => {
    const c = checkout();
    try {
      database(join(c.docker, "data/db"));
      const r = setup(c, ["--new-passwords"]);
      expect(r.status, r.stdout + r.stderr).toBe(0);
      expect(key(c.env, "POSTGRES_PASSWORD")).toMatch(/^[0-9a-f]{64}$/);
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test("--force over a database stops with .env untouched; a plain re-run and --force --new-passwords don't", () => {
    const c = checkout();
    try {
      expect(setup(c).status).toBe(0);
      database(join(c.docker, "data/db"));
      const before = sha(c.env);
      const pw = key(c.env, "POSTGRES_PASSWORD");

      const forced = setup(c, ["--force"]);
      expect(forced.status, forced.stdout + forced.stderr).toBe(1);
      expect(forced.stderr).toContain("--force makes new passwords");
      expect(sha(c.env)).toBe(before);

      const again = setup(c);
      expect(again.status, again.stdout + again.stderr).toBe(0);
      expect(key(c.env, "POSTGRES_PASSWORD")).toBe(pw);

      const meant = setup(c, ["--force", "--new-passwords"]);
      expect(meant.status, meant.stdout + meant.stderr).toBe(0);
      expect(key(c.env, "POSTGRES_PASSWORD")).not.toBe(pw);
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test("--force looks in the DATA_DIR .env names, not only ./data", () => {
    const c = checkout();
    const elsewhere = mkdtempSync(join(tmpdir(), "setup-db-data-"));
    try {
      expect(setup(c).status).toBe(0);
      writeFileSync(c.env, readFileSync(c.env, "utf8").replace(/^DATA_DIR=.*$/m, `DATA_DIR=${elsewhere}`));
      database(join(elsewhere, "db"));
      const r = setup(c, ["--force"]);
      expect(r.status, r.stdout + r.stderr).toBe(1);
      expect(r.stderr).toContain(join(elsewhere, "db"));
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
      rmSync(elsewhere, { recursive: true, force: true });
    }
  });

  test("DATA_DIR as Compose reads it: the environment first, then .env quoted, relative, with a comment", () => {
    const c = checkout();
    const elsewhere = mkdtempSync(join(tmpdir(), "setup-db-env-"));
    try {
      expect(setup(c).status).toBe(0);
      database(join(elsewhere, "db"));
      const fromEnv = setup(c, ["--force"], { DATA_DIR: elsewhere });
      expect(fromEnv.status, fromEnv.stdout + fromEnv.stderr).toBe(1);
      expect(fromEnv.stderr).toContain(join(elsewhere, "db"));

      database(join(c.docker, "mydata/db"));
      writeFileSync(c.env, readFileSync(c.env, "utf8").replace(/^DATA_DIR=.*$/m, 'export DATA_DIR="./mydata"   # moved here'));
      const quoted = setup(c, ["--force"]);
      expect(quoted.status, quoted.stdout + quoted.stderr).toBe(1);
      expect(quoted.stderr).toContain(join(c.docker, "mydata/db"));
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
      rmSync(elsewhere, { recursive: true, force: true });
    }
  });

  test("the push-key hint no longer says --force", () => {
    const src = readFileSync(join(REPO, "setup.sh"), "utf8");
    expect(src).not.toMatch(/re-run:?\s+\.?\/?setup\.sh --force/);
    for (const page of ["Notifications.md", "Quick-start.md"]) {
      expect(readFileSync(join(REPO, "docs/wiki", page), "utf8")).not.toMatch(/run `\.\/setup\.sh --force`/);
    }
  });
});

test.describe("start.sh in a folder OpenMediaVault manages", () => {
  test(".env gone beside a database: no `./setup.sh` advice, the copies instead", () => {
    const c = checkout();
    try {
      database(join(c.docker, "data/db"));
      const r = startSh(c);
      expect(r.status).toBe(1);
      expect(r.stderr).toContain(".env is missing");
      expect(r.stderr).toContain("put your copy of .env back");
      expect(r.stderr).not.toContain("run `./setup.sh`");
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test(".env gone beside an empty data/db (a failed first up): still points at ./setup.sh", () => {
    const c = checkout();
    try {
      mkdirSync(join(c.docker, "data/db"), { recursive: true });
      const r = startSh(c);
      expect(r.status).toBe(1);
      expect(r.stderr).toContain("run `./setup.sh`");
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test(".env gone, OMV's files still there: says OpenMediaVault manages the folder", () => {
    const c = checkout();
    try {
      writeFileSync(join(c.docker, "docker.yml"), OMV_HEADER + "services: {}\n");
      const r = startSh(c);
      expect(r.status).toBe(1);
      expect(r.stderr).toContain("docker.yml was written by OpenMediaVault");
      expect(r.stderr).toContain("A git\n       install and the Compose plugin");
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test(".env is OMV's link to its own copy: warns, and carries on", () => {
    const c = checkout();
    try {
      expect(setup(c).status).toBe(0);
      const copy = join(c.docker, "docker.env");
      writeFileSync(copy, OMV_HEADER + readFileSync(c.env, "utf8"));
      rmSync(c.env);
      symlinkSync(copy, c.env);
      const r = startSh(c);
      expect(r.status, r.stderr).toBe(0);
      expect(r.stderr).toMatch(/^warning: .*\.env was written by OpenMediaVault\./m);
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });

  test("an ordinary folder: no word about OpenMediaVault", () => {
    const c = checkout();
    try {
      expect(setup(c).status).toBe(0);
      const r = startSh(c);
      expect(r.status, r.stderr).toBe(0);
      expect(r.stderr).not.toContain("OpenMediaVault");
    } finally {
      rmSync(c.dir, { recursive: true, force: true });
    }
  });
});
